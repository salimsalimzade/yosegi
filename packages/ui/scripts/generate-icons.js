// Turns the SVGs in src/icons into the icon components in
// src/primitives/icons.tsx, and copies the cleaned files to the playground,
// whose Icons page offers them for download. SVGO tidies each file first:
// it drops what design tools add, and turns fixed colours into currentColor
// so every icon follows the text colour around it.
//
//   node scripts/generate-icons.js           write the files
//   node scripts/generate-icons.js --check   fail if they are out of date
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { optimize } from "svgo";

const root = new URL("..", import.meta.url);
const source = new URL("src/icons/", root);
const output = new URL("src/primitives/icons.tsx", root);
const playground = new URL("../../apps/playground/public/icons/", root);
const check = process.argv.includes("--check");

const svgo = {
  multipass: true,
  js2svg: { pretty: true, indent: 2 },
  plugins: [
    // Figma clips each frame to its own box, which an icon doesn't need.
    { name: "removeAttrs", params: { attrs: "clip-path" } },
    {
      name: "preset-default",
      params: {
        overrides: {
          // Keep circles and separate strokes as drawn, so the markup stays readable.
          convertShapeToPath: false,
          mergePaths: false,
          convertColors: { currentColor: true },
        },
      },
    },
  ],
};

/** search-off → SearchOffIcon */
const componentName = (file) => file.replace(/(^|-)([a-z0-9])/g, (_, __, char) => char.toUpperCase()) + "Icon";

const attributes = (text) => [...text.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, name, value]) => [name, value]);

function readIcon(file) {
  const name = file.slice(0, -".svg".length);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) {
    throw new Error(`src/icons/${file}: name icons in lowercase with dashes, like search-off.svg`);
  }
  const { data } = optimize(readFileSync(new URL(file, source), "utf8"), { ...svgo, path: file });
  const match = data.trim().match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/);
  if (!match) throw new Error(`src/icons/${file}: expected one <svg> element`);
  // Every copy of an icon on a page would share its ids, so masks and gradients can't work.
  if (/\sid="/.test(data))
    throw new Error(
      `src/icons/${file}: icons can't use ids (masks, gradients, clip paths); draw it with strokes and fills`,
    );

  const svgAttributes = attributes(match[1]).filter(([attr]) => !attr.startsWith("xmlns"));
  const body = match[2]
    .split("\n")
    .filter((line) => line.trim())
    .map((line) => line.replace(/\/>$/, " />"));
  return { file, name, component: componentName(name), svgAttributes, body, svg: compact(data) };
}

/** The cleaned file on one line, for the playground's downloads. */
const compact = (svg) => svg.replace(/>\s+</g, "><").trim() + "\n";

function component(icon) {
  const attrs = [
    ...icon.svgAttributes.map(([name, value]) => `${name}="${value}"`),
    'aria-hidden="true"',
    "{...props}",
  ];
  const oneLine = `    <svg ${attrs.join(" ")}>`;
  const open = oneLine.length <= 120 ? oneLine : `    <svg\n${attrs.map((attr) => `      ${attr}`).join("\n")}\n    >`;
  return [
    `/** ${icon.file} */`,
    `export function ${icon.component}(props: IconProps) {`,
    "  return (",
    open,
    ...icon.body.map((line) => `    ${line}`),
    "    </svg>",
    "  );",
    "}",
  ].join("\n");
}

const icons = readdirSync(source)
  .filter((file) => file.endsWith(".svg"))
  .sort()
  .map(readIcon);

const tsx = `// Generated by \`pnpm generate\` from src/icons/*.svg. Don't edit this file:
// change or add an SVG there and run the command again.
//
// Yosegi's icons: outlines on a 16px grid with a 1.5px stroke, in
// currentColor, so each follows the text colour around it. The components draw
// some of them, and they are exported for apps. Inbox, SearchOff and Warning
// are on a 24px grid, for the large circles in EmptyState and ErrorState.
// Each SVG matches a file in the design system's Icons group.

import type { JSX } from "@solidjs/web";

export type IconProps = Omit<JSX.SvgSVGAttributes<SVGSVGElement>, "children">;

${icons.map(component).join("\n\n")}
`;

// Every file this run owns, with what it should hold. Downloads that no longer
// have an SVG are removed.
const files = new Map([[output, tsx], ...icons.map((icon) => [new URL(`${icon.name}.svg`, playground), icon.svg])]);
const stale = existsSync(playground)
  ? readdirSync(playground)
      .filter((file) => file.endsWith(".svg") && !icons.some((icon) => `${icon.name}.svg` === file))
      .map((file) => new URL(file, playground))
  : [];

const relative = (url) => url.pathname.replace(new URL("../../", root).pathname, "");

if (check) {
  const outdated = [...files]
    .filter(([url, text]) => !existsSync(url) || readFileSync(url, "utf8") !== text)
    .map(([url]) => url);
  const problems = [
    ...outdated.map((url) => `out of date: ${relative(url)}`),
    ...stale.map((url) => `no SVG for: ${relative(url)}`),
  ];
  if (problems.length > 0) {
    console.error(`Icons are out of date. Run \`pnpm generate\`.\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`Icons are up to date (${icons.length}).`);
} else {
  mkdirSync(playground, { recursive: true });
  for (const [url, text] of files) writeFileSync(url, text);
  for (const url of stale) rmSync(url);
  console.log(
    `Generated ${icons.length} icons into ${relative(output)}${stale.length ? `, removed ${stale.length} old downloads` : ""}.`,
  );
}
